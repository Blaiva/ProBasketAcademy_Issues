fun JugadorEntity.toDomain(): Jugador = Jugador(
    jugadorId = jugadorId,
    nombre = nombre,
    telefono = telefono,
    edad = edad,
    domicilio = domicilio,
    categoriaId = categoriaId,
    tallaCamiseta = tallaCamiseta,
    numeroCamiseta = numeroCamiseta,
    estatura = estatura,
    peso = peso,
    tutorNombre = tutorNombre,
    tutorTelefono = tutorTelefono,
    tutorVinculo = tutorVinculo,
    tutorCorreo = tutorCorreo,
    estado = estado,
    docCompleta = docCompleta,
    fotoUri = fotoUri,
    actaNacimientoUri = actaNacimientoUri,
    tipoInscripcion = tipoInscripcion,
    fechaInicio = fechaInicio,
    fechaVencimiento = fechaVencimiento,
    cuota = cuota,
    totalGenerado = totalGenerado,
    totalPagado = totalPagado,
    deudaActual = deudaActual
)

fun Jugador.toEntity(userId: String): JugadorEntity = JugadorEntity(
    jugadorId = jugadorId,
    nombre = nombre,
    telefono = telefono,
    edad = edad,
    domicilio = domicilio,
    categoriaId = if (this.categoriaId == 0L) null else this.categoriaId,
    tallaCamiseta = tallaCamiseta,
    numeroCamiseta = numeroCamiseta,
    estatura = estatura,
    peso = peso,
    tutorNombre = tutorNombre,
    tutorTelefono = tutorTelefono,
    tutorVinculo = tutorVinculo,
    tutorCorreo = tutorCorreo,
    estado = estado,
    docCompleta = docCompleta,
    fotoUri = fotoUri,
    actaNacimientoUri = actaNacimientoUri,
    tipoInscripcion = tipoInscripcion,
    fechaInicio = fechaInicio,
    fechaVencimiento = fechaVencimiento,
    cuota = cuota,
    totalGenerado = totalGenerado,
    totalPagado = totalPagado,
    deudaActual = deudaActual,
    userId = userId
)

